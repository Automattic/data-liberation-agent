/** Shared state is populated by the five ordered export stages; stage-private values stay local. */
export interface ExportContext {
	options: ExportCaptureOptions;
	outputDir: string;
	capture: ScreenshotManifest;
	httpInput: ReturnType< typeof loadHttpExportInput > | undefined;
	embedded: ReturnType< typeof loadEmbeddedDocuments > | undefined;
	embeddedSources: Set< string >;
	siteSwitchWidth: number | undefined;
	phoneSwitchWidth: number | undefined;
	stageDir: string;
	budget: ExportTotalBudget;
	exclusions: ExportBudgetExclusions;
	portableMediaTotalBytesLimit: number;
	maxFileBytes: number;
	switchWidths: number[];
	deviceSelections: { url: string; id: string; documents: string[]; missing: string[]; evidence: string; }[];
	widthSelections: Array< { url: string; kind: 'width'; switchWidth: number; evidence: string } >;
	fluidReports: CaptureFluidEvidence[];
	websiteDir: string;
	capturedEntries: CaptureEntry[];
	resourceManifest: CapturedResourceManifest;
	interactionPages: InteractionStatesReport[];
	scrollStatesPages: ScrollStatesReport[];
	excludedRoutes: string[];
	routeCaptureDiagnostics: RouteDiagnostic[];
	responsiveBodyClassProjections: Map<string, { moved: ReadonlyMap<string, string>; documentClasses?: readonly string[]; }>;
	collapsedBodyClassProjections: Map<string, { moved: Map<string, string>; aliases: Map<string, string>; width: number; }>;
	entrypointUrl: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['entrypointUrl'];
	entrypointEntry: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['entrypointEntry'];
	routePathOf: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['routePathOf'];
	retainedEntries: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['retainedEntries'];
	duplicateRoutes: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['duplicateRoutes'];
	canonicalRouteAliases: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['canonicalRouteAliases'];
	portableRedirects: ReturnType< typeof allocateCaptureRoutes<CaptureEntry> >['portableRedirects'];
	semanticEvidence: ReturnType< typeof buildSemanticEvidenceArtifacts > | undefined;
	mediaStubs: ReturnType< typeof MediaStubStore.load >;
	assetReferenceLocations: ReturnType< typeof collectAssetEvidenceReferences >;
	mixedSrcsetReferences: Map<string, Set<string>>;
	mediaStage: ReturnType< typeof materializePortableMedia >;
	mediaReplacements: ReturnType< typeof materializePortableMedia >['mediaReplacements'];
	portablePathsBySource: ReturnType< typeof materializePortableMedia >['portablePathsBySource'];
	mediaAssetPaths: string[];
	portableUrlByFamily: ReturnType< typeof materializePortableMedia >['portableUrlByFamily'];
	assets: ReturnType< typeof materializePortableMedia >['assets'];
	unresolvedMedia: ReturnType< typeof materializePortableMedia >['unresolvedMedia'];
	portableMedia: ReturnType< typeof materializePortableMedia >['portableMedia'];
	resourceStage: ReturnType< typeof materializePortableResources >;
	resourceReplacements: ReturnType< typeof materializePortableResources >['resourceReplacements'];
	unresolvedDependencies: ReturnType< typeof materializePortableResources >['unresolvedDependencies'];
	rejectedReplacementKeys: ReturnType< typeof materializePortableResources >['rejectedReplacementKeys'];
	stylesheetStage: ReturnType< typeof materializeSharedStylesheets >;
	replaceMedia: ReturnType< typeof preparePortableReplacements >;
	replaceResources: ReturnType< typeof preparePortableReplacements >;
	portableMediaReplacements: Map<string, string>;
	routes: { url: string; path: string; accessGate?: AccessGateEvidence; }[];
	sourceRouteLinks: Map<string, string>;
	portableServedPaths: Set<string>;
	unresolvedAnchors: { sourceUrl: string; reason: string; fragment?: string; targetCount?: number; url?: string; }[];
	boundaryRoutes: Set<string>;
	capturedRouteKeys: Set<string>;
	absentRoutes: Set<string>;
	absentRouteKeys: Set<string>;
	omittedRouteKeys: Set<string>;
	resourceInputKeys: Set<string>;
	verifiedRouteObservations: CapturedRouteNavigation[];
	responsiveIdentities: { ids: Map<string, string | string[]>; namedAliases: boolean; svgIds: Set<string>; };
}
